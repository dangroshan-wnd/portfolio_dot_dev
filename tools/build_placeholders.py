# ------------------------------------------------------------------ paper-cutout toolkit
PAPER_DEFS = """      <defs>
        <filter id="paper" x="-10%" y="-10%" width="120%" height="130%">
          <feDropShadow dx="0" dy="5" stdDeviation="4" flood-color="#030712" flood-opacity=".55"/>
        </filter>
      </defs>"""


def cut(inner, cls=""):
    """Wrap shapes as one paper layer (drop shadow)."""
    c = f' class="{cls}"' if cls else ""
    return f'<g filter="url(#paper)"{c}>{inner}</g>'


def zigzag(y, fill, step=30, depth=14, x0=0, x1=1200):
    pts = [f"M{x0} {y}"]
    x, up = x0, True
    while x < x1:
        x += step
        pts.append(f"L{x} {y - depth if up else y}")
        up = not up
    return f'<path d="{" ".join(pts)} V800 H{x0}Z" fill="{fill}"/>'


def waves(y, fill, amp=10, length=120, x0=-120, x1=1320):
    d = [f"M{x0} {y}"]
    x = x0
    while x < x1:
        d.append(f"q{length / 4} {-amp} {length / 2} 0 t{length / 2} 0")
        x += length
    return f'<path d="{" ".join(d)} V800 H{x0}Z" fill="{fill}"/>'


def stars(points, fill=PAPER_CREAM):
    return "\n".join(
        f'      <circle class="twinkle" cx="{x}" cy="{y}" r="{r}" fill="{fill}" style="animation-delay:-{(i * .37) % 2.4:.2f}s"/>'
        for i, (x, y, r) in enumerate(points))


